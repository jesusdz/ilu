#ifndef SCRIPT_H
#define SCRIPT_H

constexpr u32 MAX_SCRIPTS = 64;
constexpr u32 MAX_SCRIPT_PROPERTIES = 32;
constexpr u32 MAX_ENTITY_SCRIPTS = 4;

// Structs tagged ILU_STRUCT(Script) are the ones that can be registered as scripts
#define SCRIPT_HINT "Script"
constexpr u32 MAX_SCRIPT_INSTANCES = 1024;
constexpr u32 SCRIPT_INSTANCE_ALIGN = 16;
constexpr u32 SCRIPT_INSTANCE_DATA_SIZE = MAX_SCRIPT_INSTANCES * 128; // 128K

enum ScriptHookType
{
	ScriptHook_Start,
	ScriptHook_Simulate,
	ScriptHook_Update,
	ScriptHook_Stop,
	ScriptHook_Count,
};

typedef ReflexFunctor ScriptHook;

struct ScriptPropertyDesc
{
	const char *name;
	PropertyValue value;
};

struct ScriptDesc
{
	ID entity; // Owner entity
	const char *name;
	u32 propertyCount;
	ScriptPropertyDesc properties[MAX_SCRIPT_PROPERTIES];
};

struct Script
{
	const ReflexStruct *type; // Layout and properties, generated by reflex
	ScriptHook hooks[ScriptHook_Count];
};

inline const char *ScriptName(const Script &script)
{
	return script.type->name;
}

inline u32 ScriptInstanceSize(const Script &script)
{
	return AlignUp((u32)script.type->size, SCRIPT_INSTANCE_ALIGN);
}

struct ScriptInstance
{
	ID entity; // Owner entity (invalid means remove the instance)
	const char *scriptName;
	u32 offset; // Offset into the data blob
	u32 size; // To compare against new hot-reloaded data
	u16 structIndex;
};

////////////////////////////////////////////////////////////////////////
// Binary data

#pragma pack(push, 1)

struct BinScriptPropertyDesc
{
	const char *name;
	ReflexID type;
	u32 value; // Raw view of PropertyValue, whichever member the type selects
};

struct BinScriptDesc
{
	ID entity;
	const char *name;
	BinLocation properties;
};

struct BinScript
{
	BinScriptDesc *desc;
	BinScriptPropertyDesc *properties;
};

#pragma pack(pop)

#endif // SCRIPT_H
